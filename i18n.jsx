function detectLang() {
  try {
    const saved = localStorage.getItem('odemes_lang');
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (_) {}
  const nav = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (nav.startsWith('pt')) return 'pt';
  if (nav.startsWith('es')) return 'es';
  if (nav.startsWith('fr')) return 'fr';
  return 'en';
}

// Sync global for non-React code (data.jsx)
window._i18nLang = detectLang();

const _LangContext = React.createContext(null);

function LangProvider({ children }) {
  const [lang, setLangState] = React.useState(detectLang);

  React.useEffect(() => {
    window._i18nLang = lang;
    document.documentElement.setAttribute('lang', lang);
    // Update the real browser tab title
    const titles = { en: 'Odemes — Personal Finance', pt: 'Odemes — Finanças Pessoais', es: 'Odemes — Finanzas Personales', fr: 'Odemes — Finances Personnelles' };
    document.title = titles[lang] || titles.en;
  }, [lang]);

  const setLang = (l) => {
    if (!TRANSLATIONS[l]) return;
    try { localStorage.setItem('odemes_lang', l); } catch (_) {}
    setLangState(l);
  };

  const t = React.useCallback((key) => {
    const parts = key.split('.');
    let val = TRANSLATIONS[lang];
    for (const k of parts) {
      if (val == null || typeof val !== 'object') { val = undefined; break; }
      val = val[k];
    }
    if (typeof val === 'string') return val;
    // Fallback to English
    val = TRANSLATIONS.en;
    for (const k of parts) {
      if (val == null || typeof val !== 'object') { val = undefined; break; }
      val = val[k];
    }
    return typeof val === 'string' ? val : key;
  }, [lang]);

  return (
    <_LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </_LangContext.Provider>
  );
}

function useT() {
  return React.useContext(_LangContext);
}

window.I18n = { LangProvider, useT, TRANSLATIONS };
